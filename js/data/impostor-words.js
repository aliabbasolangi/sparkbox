export function buildWordPool(selectedGenreIds) {
  const pool = [];
  for (const genre of IMPOSTOR_GENRES) {
    if (!selectedGenreIds.includes(genre.id)) continue;
    for (const entry of genre.words) {
      pool.push({ ...entry, genre: genre.name });
    }
  }
  return pool;
}
